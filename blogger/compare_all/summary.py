# -*- coding: utf-8 -*-
"""⑦ 写总结 —— 报告末尾那一段「总结与分析」（见 04§1、§5）。

**这是全博主对比里唯一用模型的地方。** 它读的就是前六节已经算好的东西 ——
数字一个都不许它自己算、自己编，只准对着给它的表格说话。

**只讲三件事**：谁强谁弱、哪些名次因样本问题不可信、与上一版的明显变化。
没有上一版（第一次跑）就说这是第一版。
"""

from __future__ import annotations

from blogger.common import ds

SYSTEM_PROMPT = """你在给一份「全博主对比」报告写结尾的总结与分析。

**规矩**：

1. **只准用给你的表格里的数字，一个都不许自己算、自己估、自己补。**
   表里没有的，就不写。
2. **只讲三件事**，按这个顺序：
   - **谁强谁弱** —— 点名，给数字。
   - **哪些名次不可信** —— 样本集中、有缺口、信号条数刚过线的，逐条点名。
   - **与上一版的明显变化** —— 谁上来了、谁掉下去了。没有上一版就说这是第一版。
3. **不写套话** —— 不写「建议投资者谨慎」「市场有风险」这类。不写「综上所述」。
4. 全程中文，不要 emoji，不要标题层级，就是几段话。
5. 篇幅控制在 400 字以内。

**输出格式**：一个 JSON 对象，只有一键 —— `{"总结": "那几段话"}`。段与段之间用空行隔开。
除了这个 JSON 什么都不要输出。"""


def write(body: str, previous: str, log=print) -> str:
    """`body` 是脚本拼好的 ①～⑥ 全文；`previous` 是上一版报告（没有就是空串）。

    **模型调不通不算这一轮失败** —— 报告 ①～⑥ 照出，只在第 ⑦ 段注明没写出来。
    """
    user = ["这是本次算好的报告全文：", "", body, ""]
    if previous.strip():
        user += ["这是上一版的报告（用来比变化）：", "", previous, ""]
    else:
        user += ["**没有上一版** —— 这是第一版，第三件事就写这一句。", ""]
    try:
        got = ds.call_json(SYSTEM_PROMPT,
                           "\n".join(user) + "\n请把结尾那一段总结与分析给我。",
                           label="全博主总结")
    except ds.ModelError as e:
        log(f"  第 ⑦ 段没写出来：{e}")
        return f"（这一段没写出来：{e}）"

    text = (got or {}).get("总结") or (got or {}).get("text") or ""
    if not text.strip():
        log("  第 ⑦ 段没写出来：模型没给出可用的正文")
        return "（这一段没写出来：模型没给出可用的正文）"
    return text.strip()


__all__ = ["write"]
